import type { LocaleT } from '../config'

/**
 * Primary-sidebar labels, ported verbatim from website-city's
 * `locales/<lang>/nav.json` (`nav.sections.*`, `nav.items.*.label` and
 * `nav.sidebar.*`) so the two rails read identically in all nine languages.
 *
 * Keys mirror city's, minus the `.label` leaf its catalogue carries for the
 * header's sub-labels: `sections.<name>` for a group heading, `items.<name>`
 * for a leaf, `share.title` / `share.desc` for the bottom call-to-action. The
 * shape is nested so `getT` can resolve it by dot-path.
 *
 * Keep in sync with website-city's `SIDEBAR_SECTIONS`
 * (`src/app/_components/ui/shell/nav-config.ts`) — that config is the source of
 * truth for which entries the rail shows and in what order; this file only
 * carries their text.
 *
 * City now translates every one of these keys itself, so nothing here is
 * English-only any more (`overview`, `maps`, `activity`, `media`, `messages`,
 * `myFriends`, `myGroups` and the Groups / Community / External Sources
 * headings used to be, because city carried them in English alone). A key city
 * ever carries in English alone must STAY English here too: its request
 * pipeline merges English under every locale, so translating one on this side
 * alone would make the landing site's rail read DIFFERENTLY from the app's in
 * the other eight languages, which is exactly what this catalogue exists to
 * prevent. `getT` falls back to English per key, so a gap never leaks a raw key.
 */
export type SidebarCatalog = Record<
    LocaleT,
    {
        sections?: Record<string, string>
        items?: Record<string, string>
        /**
         * Sub-labels for the header's pillar dropdowns, keyed
         * `<section>.<leaf>` — "Browse" reads the same in every section but
         * means something different in each, so the copy cannot hang off the
         * shared `items.*` label. Mirrors city's `nav.pillars.*`.
         */
        pillars?: Record<string, Record<string, string>>
        share?: Record<string, string>
    }
>

